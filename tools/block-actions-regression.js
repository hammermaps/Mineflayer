const assert = require('node:assert/strict')
const { EventEmitter } = require('node:events')
const { Vec3 } = require('vec3')
const bot = new EventEmitter()
bot._client = new EventEmitter()
bot.registry = { instruments: [], blocks: { 1: { name: 'ender_chest' } } }
const position = new Vec3(1, 2, 3)
const chest = { name: 'ender_chest', position }
bot.blockAt = () => chest
require('../lib/plugins/block_actions')(bot)
let count = 0
bot.on('chestLidMove', () => count++)
const open = () => bot._client.emit('block_action', { location: position, blockId: 1, byte2: 1 })
open()
open()
assert.equal(count, 1, 'duplicate open suppressed')
bot.emit('blockUpdate', chest, { ...chest })
open()
assert.equal(count, 1, 'same block keeps count')
bot.emit('blockUpdate', chest, null)
open()
assert.equal(count, 1, 'unloaded block safely ignored')
bot.emit('blockUpdate', chest, { name: 'air', position })
open()
assert.equal(count, 2, 'replacement clears stale count')
bot._client.emit('block_action', { location: position, blockId: 1, byte2: 0 })
open()
assert.equal(count, 4, 'normal close allows reopen')
console.log('5 block-action regressions passed')
